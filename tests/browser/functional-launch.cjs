const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {chromium}=require(process.env.NUGGETFINDER_PLAYWRIGHT||'playwright');
const {startReview}=require('../../scripts/review-server.cjs');

(async()=>{
 process.env.NUGGETFINDER_REVIEW_ONLY='1';
 process.env.NUGGETFINDER_REVIEW_PUBLISH_PHOTOS='1';
 for(const width of [390,1280]){
  const review=await startReview({port:0,unified:true});
  let browser;
  try{
   browser=await chromium.launch({args:['--single-process','--disable-gpu']});
   const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'});
   const page=await context.newPage();
   const errors=[],external=[];
   page.setDefaultTimeout(10000);
   page.on('pageerror',error=>errors.push(error.message));
   page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
   page.on('request',request=>{if(/^https?:/.test(request.url())&&!request.url().startsWith(review.url+'/'))external.push(request.url());});
   await page.route('**/*tiles/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#ede9dc"/><text x="10" y="125" font-size="12">Test tile</text></svg>'}));
   async function go(hash){await page.goto(review.url+'/index.html#/'+hash);}
   async function shot(name){
    await page.evaluate(()=>document.fonts.ready);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width,name);
    const dir=path.resolve(__dirname,'../../docs/screenshots/functional-launch',name);
    await fs.mkdir(dir,{recursive:true});
    await page.screenshot({path:path.join(dir,width+'.png')});
   }
   async function role(value){
    await page.locator('#reviewControls summary').click();
    await page.locator('[data-role]').selectOption(value);
    await page.waitForFunction(role=>sessionStorage.getItem('nugget-review-role')===role,value);
   }
   assert.equal((await review.db.pool.query('select cutover from runtime_controls')).rows[0].cutover,true);
   await assert.rejects(review.db.actor(2,"select submit_stock_report('mcnuggets','node/1229920544','seen')"),/participant_session_required/);
   await go('suggest-product?place=node%2F1229920544');
   await page.locator('[name=name]').fill('Fixture Frozen Nuggets');
   await page.locator('[name=brand]').fill('Fixture Brand');
   await page.waitForFunction(()=>!!window.NuggetfinderParticipant?.current());
   const token=await page.evaluate(()=>NuggetfinderParticipant.current().participant);
   await shot('product-suggestion');
   await page.getByRole('button',{name:'Send',exact:true}).click();
   await page.getByRole('status').filter({hasText:'Suggestion saved'}).waitFor();
   await go('activity');
   await page.getByText('Fixture Frozen Nuggets',{exact:true}).waitFor();
   await shot('pending-status');
   await role('mod');
   await page.goto(review.url+'/crew.html#mod');
   const card=page.locator('.place-review .wave-card').filter({hasText:'Fixture Frozen Nuggets'});
   await card.locator('input').check();
   await shot('moderation');
   await card.getByRole('button',{name:'Approve',exact:true}).click();
   await page.getByText('No pending catalog requests.',{exact:true}).waitFor();
   const product=(await review.db.pool.query("select id from products where name='Fixture Frozen Nuggets'")).rows[0].id;
   await go('product/'+product);
   await role('a');
   await page.waitForFunction(()=>document.querySelector('#who')?.textContent.includes('crunch_captain'));
   assert.equal(await page.evaluate(()=>NuggetfinderParticipant.current().participant),token);
   const store=page.locator('[data-place="node/1229920544"]');
   await store.getByRole('button',{name:'Seen it',exact:true}).click();
   await store.getByText('UNCONFIRMED',{exact:false}).waitFor();
   await store.getByRole('link',{name:'Attach shelf photo'}).click();
   await page.locator('[data-library]').waitFor();
   const png=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=480;canvas.height=360;const c=canvas.getContext('2d');c.fillStyle='#f4b223';c.fillRect(0,0,480,360);c.fillStyle='#161514';c.font='24px sans-serif';c.fillText('TEST NUGGET BOX',40,120);return canvas.toDataURL('image/png').split(',')[1];});
   await page.locator('[data-library]').setInputFiles({name:'fixture.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
   await page.locator('[data-attest]').check();
   await page.locator('[data-prepare]').click();
   await page.locator('[data-upload]').click();
   await page.getByRole('status').filter({hasText:'Food photo saved privately'}).waitFor();
   await shot('stock-evidence');
   const owner=(await review.db.pool.query('select e.participant_id,p.profile_id,s.user_id from photo_evidence e join participant_profiles p on p.participant_id=e.participant_id join photo_evidence_links l on l.evidence_id=e.id join stock_reports s on s.id::text=l.content_ref')).rows[0];
   assert.equal(owner.participant_id,token);assert.equal(owner.profile_id,owner.user_id);
   await page.reload();
   await page.waitForFunction(()=>NuggetfinderParticipant.current());
   assert.equal(await page.evaluate(()=>NuggetfinderParticipant.current().participant),token);
   await go('product/'+product);
   await role('b');
   await page.waitForFunction(()=>document.querySelector('#who')?.textContent.includes('sauce_counsel'));
   await store.getByRole('button',{name:'Seen it',exact:true}).click();
   await store.getByText('IN STOCK',{exact:false}).waitFor();
   await shot('confirmed-stock');
   await go('take?kind=product&ref='+product);
   await page.locator('#takeTarget').selectOption(product);
   await page.locator('#takeText').fill('This test crunch deserves a trophy.');
   await page.getByRole('button',{name:'Prepare a food photo'}).click();
   await page.locator('[data-library]').setInputFiles({name:'fixture-take.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
   await page.locator('[data-attest]').check();
   await page.locator('[data-prepare]').click();
   await page.getByText('Photo ready. Post your take to send it for review.',{exact:true}).waitFor();
   await page.getByRole('button',{name:'Post',exact:true}).click();
   await page.getByText('Take and photo sent for review.',{exact:true}).waitFor();
   const joined=await review.db.pool.query("select e.status from photo_evidence e join photo_evidence_links l on l.evidence_id=e.id join takes t on t.id::text=l.content_ref where l.kind='take' and t.body='This test crunch deserves a trophy.'");
   assert.deepEqual(joined.rows,[{status:'pending'}]);
   await shot('take-evidence');
   await go('business');
   await role('business');
   await page.waitForFunction(()=>NuggetfinderParticipant.current());
   await page.locator('[name=place]').selectOption('node/1229920544');
   await page.locator('[name=source]').fill('https://example.org/store');
   await shot('business-claim');
   await page.getByRole('button',{name:'Send',exact:true}).click();
   await page.getByRole('status').filter({hasText:'Suggestion saved'}).waitFor();
   await role('mod');
   await page.goto(review.url+'/crew.html#mod');
   const claim=page.locator('.place-review .wave-card').filter({hasText:'store claim'});
   await claim.locator('input').check();
   await claim.getByRole('button',{name:'Approve',exact:true}).click();
   await page.getByRole('button',{name:'Revoke business access',exact:true}).waitFor();
   await go('business');
   await role('business');
   await page.waitForFunction(()=>NuggetfinderParticipant.current());
   await page.locator('[name=kind]').selectOption('stock');
   await page.locator('[name=place]').selectOption('node/1229920544');
   await page.locator('[name=product]').selectOption(product);
   await page.getByRole('button',{name:'Send',exact:true}).click();
   await page.getByRole('status').filter({hasText:'Verified business report saved'}).waitFor();
   await go('product/'+product);
   await page.getByText(/Verified store report/).waitFor();
   await shot('business-stock');
   await page.locator('#authBtn').click();
   await page.getByRole('button',{name:'CONNECT PLAYER',exact:true}).waitFor();
   await page.reload();
   await page.getByRole('button',{name:'CONNECT PLAYER',exact:true}).waitFor();
   assert.equal(await page.evaluate(()=>NuggetfinderParticipant.current()),null);
   await page.emulateMedia({reducedMotion:'no-preference'});
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width);
   assert.deepEqual(errors,[]);
   assert.deepEqual(external,[]);
   console.log(width+': shopper submission, review, shared report/photo identity, refresh, separate stock confirmation, take photo and verified business reporting passed');
  }finally{if(browser)await browser.close();await review.close();}
 }
})().catch(error=>{console.error(error);process.exitCode=1;});
